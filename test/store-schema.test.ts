// The schema each database server gets, compiled without a server: the column types that keep a
// body's bytes and a text's exact value, and the ids each server numbers itself. The databases job
// runs the same migrations against real servers.
import { describe, expect, it } from "vitest";

import {
  DummyDriver,
  Kysely,
  MssqlAdapter,
  MssqlIntrospector,
  MssqlQueryCompiler,
  MysqlAdapter,
  MysqlIntrospector,
  MysqlQueryCompiler,
  PostgresAdapter,
  PostgresIntrospector,
  PostgresQueryCompiler,
  SqliteAdapter,
  SqliteIntrospector,
  SqliteQueryCompiler,
  type Dialect,
} from "kysely";

import { migrations } from "../src/storage/store.js";

const DIALECTS = {
  sqlite: [SqliteAdapter, SqliteIntrospector, SqliteQueryCompiler],
  postgres: [PostgresAdapter, PostgresIntrospector, PostgresQueryCompiler],
  mysql: [MysqlAdapter, MysqlIntrospector, MysqlQueryCompiler],
  sqlserver: [MssqlAdapter, MssqlIntrospector, MssqlQueryCompiler],
} as const;

async function schemaFor(kind: keyof typeof DIALECTS): Promise<string[]> {
  const [Adapter, Introspector, Compiler] = DIALECTS[kind];
  const dialect: Dialect = {
    createAdapter: () => new Adapter(),
    createDriver: () => new DummyDriver(),
    createIntrospector: (db) => new Introspector(db),
    createQueryCompiler: () => new Compiler(),
  };
  const statements: string[] = [];
  const db = new Kysely<unknown>({
    dialect,
    log: (event) => {
      statements.push(event.query.sql);
    },
  });
  for (const migration of Object.values(migrations(kind))) await migration.up(db);
  await db.destroy();
  return statements;
}

const KINDS = Object.keys(DIALECTS) as (keyof typeof DIALECTS)[];

describe("the schema on each database", () => {
  it("runs the same steps under the same names everywhere", async () => {
    const names = KINDS.map((kind) => Object.keys(migrations(kind)));
    for (const list of names) expect(list).toEqual(names[0]);
    const counts = await Promise.all(KINDS.map(async (kind) => (await schemaFor(kind)).length));
    expect(new Set(counts).size).toBe(1);
  });

  it("stores bodies as bytes and numbers rows itself, in each database's own words", async () => {
    const [sqlite, postgres, mysql, sqlserver] = await Promise.all(
      KINDS.map(async (kind) => (await schemaFor(kind))[0]),
    );
    expect(sqlite).toBe(
      'create table "messages" ("id" integer primary key autoincrement, "channel" text not null, "received_at" text not null, "body" blob not null, "status" text not null, "error" text, "updated_at" text not null)',
    );
    expect(postgres).toBe(
      'create table "messages" ("id" bigint generated by default as identity primary key, "channel" text not null, "received_at" text not null, "body" bytea not null, "status" text not null, "error" text, "updated_at" text not null)',
    );
    expect(mysql).toBe(
      "create table `messages` (`id` bigint primary key auto_increment, `channel` varchar(255) not null, `received_at` varchar(32) not null, `body` longblob not null, `status` varchar(32) not null, `error` mediumtext, `updated_at` varchar(32) not null) engine = InnoDB default character set utf8mb4 collate utf8mb4_bin",
    );
    expect(sqlserver).toBe(
      'create table "messages" ("id" bigint identity primary key, "channel" nvarchar(255) collate Latin1_General_100_BIN2 not null, "received_at" nvarchar(32) not null, "body" varbinary(max) not null, "status" nvarchar(32) collate Latin1_General_100_BIN2 not null, "error" nvarchar(max) collate Latin1_General_100_BIN2, "updated_at" nvarchar(32) not null)',
    );
  });

  it("compares text byte for byte on MySQL and SQL Server, in every table and added column", async () => {
    const mysql = await schemaFor("mysql");
    const tables = mysql.filter((statement) => statement.startsWith("create table"));
    expect(tables).toHaveLength(6);
    for (const table of tables) {
      expect(table).toMatch(
        /\) engine = InnoDB default character set utf8mb4 collate utf8mb4_bin$/,
      );
    }
    const sqlserver = await schemaFor("sqlserver");
    // Every text column but the times carries the binary collation, so case and accents count.
    const texts = sqlserver.flatMap(
      (statement) => statement.match(/nvarchar\((?:255|max)\)[^,)]*/g) ?? [],
    );
    expect(texts.length).toBeGreaterThan(0);
    for (const column of texts) expect(column).toContain("collate Latin1_General_100_BIN2");
    // Row ids and sizes are 64-bit on every server.
    for (const statements of [await schemaFor("postgres"), mysql, sqlserver]) {
      expect(statements.join("\n")).not.toMatch(
        /"id" integer|`id` integer|"size" integer|`size` integer/,
      );
    }
  });
});
